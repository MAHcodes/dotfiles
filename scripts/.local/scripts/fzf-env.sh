# Shared fzf environment: static defaults plus the DMS/matugen-generated
# colours. Sourced by interactive zsh and by tmux launchers (e.g.
# tmux-sessionizer) so both get the same defaults and theming.
# Keep this file POSIX/bash/zsh compatible.

# prefer fd when it is installed, fall back to find otherwise
if command -v fd >/dev/null 2>&1; then
  export FZF_DEFAULT_COMMAND='fd --type f --hidden --follow --exclude .git'
  _fzf_dir_command='fd --type d --hidden --follow --exclude .git'
else
  export FZF_DEFAULT_COMMAND='find . -type f -not -path "*/.git/*"'
  _fzf_dir_command='find . -type d -not -path "*/.git/*"'
fi

export FZF_DEFAULT_OPTS=" \
--border=none --margin=0 --padding=0 --info=inline --prompt=' ' --ansi --no-mouse --reverse \
  --bind 'ctrl-d:change-prompt( )+reload($_fzf_dir_command)' \
  --bind 'ctrl-f:change-prompt( )+reload($FZF_DEFAULT_COMMAND)'"

export FZF_ALT_C_COMMAND="$_fzf_dir_command"
unset _fzf_dir_command

# Colours are generated by matugen/DMS and read on every fzf invocation, so
# theme changes apply to already-running shells too. Guard the path because
# fzf errors out when the file is missing.
if [ -r "$HOME/.local/state/dms/fzf-theme.opts" ]; then
  export FZF_DEFAULT_OPTS_FILE="$HOME/.local/state/dms/fzf-theme.opts"
fi
